"""
Run inside ChimeraX:  chimerax --nogui --exit --cmd "runscript validate_structures.py"

Opens every structure in cdk_config.STRUCTURES and checks that
  (a) the chain assignments are right (prints chain descriptions / lengths),
  (b) the residue present at each hit position matches the wild-type amino acid
      recorded in the HGVSp string (i.e. PDB auth numbering == screen numbering),
  (c) reports which hit positions are missing from the model (disordered loops),
  (d) lists the HET/ligand residues in the kinase chain.
"""
import csv, os, sys
from chimerax.core.commands import run

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cdk_config import STRUCTURES

THREE_TO_ONE = {
    'ALA':'A','ARG':'R','ASN':'N','ASP':'D','CYS':'C','GLN':'Q','GLU':'E','GLY':'G',
    'HIS':'H','ILE':'I','LEU':'L','LYS':'K','MET':'M','PHE':'F','PRO':'P','SER':'S',
    'THR':'T','TRP':'W','TYR':'Y','VAL':'V','SEP':'S','TPO':'T','PTR':'Y','MSE':'M',
}

hits = list(csv.DictReader(open(os.path.join(HERE, "hit_residues.csv"))))

run(session, "close session")
summary = []
report = []
unmodelled = []
for gene, cfg in STRUCTURES.items():
    path = os.path.join(HERE, "structures", cfg["file"])
    models = run(session, f"open {path}")
    m = models[0]
    print(f"\n=== {gene}  ({cfg['pdb']})  {cfg['note']}")
    for ch in m.chains:
        res = ch.existing_residues
        print(f"    chain {ch.chain_id:2s} n={len(res):5d} range={res[0].number}-{res[-1].number}"
              f" {'<-- KINASE' if ch.chain_id==cfg['kinase_chain'] else ''}"
              f"{'  <-- CYCLIN' if ch.chain_id in cfg['cyclin_chains'] else ''}")
    kc = cfg["kinase_chain"]
    bynum = {r.number: r for r in m.residues if r.chain_id == kc}
    het = sorted({(r.number, r.name) for r in m.residues
                  if r.chain_id == kc and r.name not in THREE_TO_ONE and r.name != 'HOH'})
    print(f"    HET in chain {kc}: {het}")
    ok = bad = missing = 0
    for h in (x for x in hits if x["gene"] == gene):
        pos, wt = int(h["position"]), h["wt"]
        r = bynum.get(pos)
        if r is None:
            print(f"    MISSING  {gene} {h['variant']:10s} (pos {pos} not modelled)")
            unmodelled.append((gene, pos, h["variant"]))
            missing += 1
        elif THREE_TO_ONE.get(r.name) != wt:
            print(f"    MISMATCH {gene} {h['variant']:10s} structure has {r.name} at {pos}")
            bad += 1
        else:
            ok += 1
    print(f"    --> {ok} match, {bad} mismatch, {missing} not modelled")
    summary.append((gene, ok, bad, missing))
    run(session, "close session")

print("\n=== SUMMARY (gene, matched, mismatched, unmodelled) ===")
for s in summary:
    print("   ", s)

# generate_cxc.py reads this to decide which hits cannot be drawn
with open(os.path.join(HERE, "unmodelled_positions.txt"), "w") as fh:
    fh.write("# hit positions that are absent from the chosen structure\n"
             "# (disordered loops); regenerated by validate_structures.py\n")
    for gene, pos, var in sorted(set(unmodelled)):
        fh.write(f"{gene} {pos}\n")

with open(os.path.join(HERE, "validation_report.txt"), "w") as fh:
    fh.write("gene\tmatched\tmismatched\tunmodelled\n")
    for g, ok, bad, miss in summary:
        fh.write(f"{g}\t{ok}\t{bad}\t{miss}\n")
    fh.write("\nunmodelled variants (position absent from the structure):\n")
    for gene, pos, var in sorted(set(unmodelled)):
        fh.write(f"  {gene} {var} (residue {pos})\n")
print("wrote unmodelled_positions.txt and validation_report.txt")
