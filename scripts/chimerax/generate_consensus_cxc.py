"""
Project the recurrent cross-CDK resistance positions onto a SINGLE structure.

The per-gene panels from generate_cxc.py show each CDK's own hits on its own
structure.  This script instead takes the alignment columns that carry resistance
in several CDKs at once and draws them all on one reference kinase, so the
recurrent sites can be read as a single pattern rather than compared across nine
panels.

Input : data/processed/lfc_fdr_tables/resistance_patterns/<set>/MSA_recurrent_columns.csv
        (written by notebooks/09_analysis_and_viz/CDK_resistance_patterns.ipynb)
Output: cxc_<set>_consensus/consensus.cxc, consensus_labeled.cxc, render_all.cxc

Spheres are coloured by how many CDKs carry resistance at that aligned position,
and positions that fall in a gap of the KLIFS numbering are outlined in a second
colour ramp so they stay distinguishable from numbered pocket positions.

    python3 generate_consensus_cxc.py --set core7
    python3 generate_consensus_cxc.py --set all9 --reference CDK2
"""
import argparse, collections, csv, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from cdk_config import (STRUCTURES, CDK_COLORS, CYCLIN_COLOR, OTHER_CHAIN_COLOR,
                        NONCATALYTIC_TRANSPARENCY, RENDER_PREAMBLE, CANONICAL_VIEW,
                        ZOOM_OUT, WINDOW_SIZE)

# red ramp for numbered KLIFS pocket positions, blue-grey ramp for KLIFS gaps
# index 1 is a strong singleton (one CDK, large reproducible effect); 2+ is the
# number of CDKs sharing the aligned position
POCKET_RAMP = {1: "#fee5d9", 2: "#fcae91", 3: "#fb6a4a", 4: "#cb181d", 5: "#67000d"}
GAP_RAMP = {1: "#eff3ff", 2: "#c6dbef", 3: "#6baed6", 4: "#2171b5", 5: "#08306b"}


def ramp(d, n):
    return d[min(max(n, 1), 5)]


def load_recurrent(path, reference, min_cdks, tiers=("recurrent",)):
    rows = []
    for r in csv.DictReader(open(path)):
        n = int(r["n_cdks"])
        tier = r.get("tier", "recurrent")
        if tier not in tiers:
            continue
        if tier == "recurrent" and n < min_cdks:
            continue
        # "CDK7:L18;CDK9:I25;CDK2:I10;..." -> the reference kinase's residue
        resi = None
        for bit in r["residues"].split(";"):
            g, _, aa_num = bit.partition(":")
            if g == reference:
                resi = int(aa_num[1:])
                break
        if resi is None:
            continue                       # reference has a gap at this column
        in_klifs = r["in_KLIFS"].lower() == "true"
        # gaps get their segment name ("III:aC") rather than a bare "gap"
        seg = (r.get("segment") or "").strip()
        reg = (r.get("region") or "").strip()
        if in_klifs:
            label = r["KLIFS_idx"]
        elif seg:
            label = seg                       # named gap between two KLIFS elements
        elif reg == "C-lobe post-pocket":
            label = "C-lobe"
        else:
            label = "gap"
        rows.append(dict(aln_col=int(r["aln_col"]), n_cdks=n, resi=resi, tier=tier,
                         in_klifs=in_klifs, cdks=r["cdks"], label=label,
                         max_LFC=float(r.get("max_LFC") or 0)))
    return sorted(rows, key=lambda r: -r["n_cdks"])


def build(rows, reference, labeled, label_min=3):
    cfg = STRUCTURES[reference]
    kc = cfg["kinase_chain"]
    cyc = cfg["cyclin_chains"]
    other = cfg["other_chains"]
    lo, hi = cfg["kd"]
    L = []
    L.append("# " + "=" * 74)
    L.append(f"# Recurrent CDK resistance positions projected onto {reference} "
             f"({cfg['pdb']}).")
    L.append("# Generated by generate_consensus_cxc.py -- edit that script, not this file.")
    L.append(f"# {len(rows)} aligned positions, each carrying resistance in >=2 CDKs.")
    L.append("# Sphere colour = number of CDKs; reds = numbered KLIFS position, "
             "blues = KLIFS gap.")
    L.append("# " + "=" * 74)
    L.append("close session")
    L.append(f"cd {HERE}")
    L.append("")
    L.append(f"open structures/{cfg['file']} name {reference}")
    L.append("hide #1 target acsb")
    L.append(f"show #1/{kc} cartoon")
    L.append(f"color #1/{kc} {CDK_COLORS[reference]} target c")
    L.append(f"transparency #1/{kc} & ~:{lo}-{hi} {NONCATALYTIC_TRANSPARENCY} cartoons")
    if cyc:
        cs = f"#1/" + ",".join(cyc)
        L.append(f"# {cfg['cyclin_name']} as surface")
        L.append(f"show {cs} atoms")
        L.append(f"surface {cs}")
        L.append(f"hide {cs} atoms")
        L.append(f"color {cs} {CYCLIN_COLOR} target s")
        # the consensus view has sites on the cyclin face, so the surface is made
        # see-through rather than opaque as in the single-kinase panels
        L.append(f"transparency {cs} 55 surfaces")
    if cfg["ligand"]:
        ls = f"#1/{kc} & :{cfg['ligand']}"
        L.append(f"show {ls} target ab")
        L.append(f"style {ls} stick")
        L.append(f"color {ls} #909090 target ab")
        L.append(f"color {ls} byhetero")
        if reference == "CDK2":
            L.append(f"show #1/{kc} & :MG atoms")
            L.append(f"style #1/{kc} & :MG sphere")
            L.append(f"size #1/{kc} & :MG atomRadius 0.8")
    if other:
        L.append(f"color #1/" + ",".join(other) + f" {OTHER_CHAIN_COLOR}")

    L.append("\n# ---------------------------------------- recurrent aligned positions")
    by_bucket = collections.defaultdict(list)
    for r in rows:
        # strong singletons get the palest shade of their ramp
        shade = 1 if r["tier"] == "strong_singleton" else min(r["n_cdks"], 5)
        by_bucket[(r["in_klifs"], shade)].append(r)
    for (in_klifs, n), group in sorted(by_bucket.items(), key=lambda kv: (-kv[0][1], kv[0][0])):
        resis = ",".join(str(r["resi"]) for r in sorted(group, key=lambda r: r["resi"]))
        col = ramp(POCKET_RAMP if in_klifs else GAP_RAMP, n)
        kind = ("KLIFS position" if in_klifs else "KLIFS gap") + \
               (" (strong singleton)" if n == 1 else "")
        names = ", ".join(f'{r["label"]}({r["resi"]})' for r in group)
        L.append(f"# {n} CDKs, {kind}: {names}")
        sel = f"#1/{kc}:{resis}"
        L.append(f"show {sel} atoms")
        L.append(f"cartoon {sel} suppressBackboneDisplay false")
        L.append(f"style {sel} sphere")
        L.append(f"color {sel} {col} target ac")
    allres = ",".join(str(r["resi"]) for r in sorted(rows, key=lambda r: r["resi"]))
    L.append(f"name recurrent_sites #1/{kc}:{allres}")

    L.append("\n# ---------------------------------------------------- look and camera")
    L.extend(RENDER_PREAMBLE.strip().splitlines())
    L.append("show #* models")
    L.append("label delete")
    L.append("hide #* target p")
    L.append("hide @@element=H target ab")
    L.append(f"view matrix camera {CANONICAL_VIEW}")
    # leaves room in the left/right gutters for leader-line labels
    L.append("zoom 0.88")

    if labeled:
        L.append("\n# ------------------------------------------------- residue labels")
        L.append("# every recurrent position is labelled with its KLIFS index (or 'gap'),")
        L.append("# so the pattern can be read without cross-referencing the table")
        # labelling all 25 sites makes the cleft unreadable, so only the positions
        # shared by >= `label_min` CDKs are named; the rest stay coloured spheres
        for r in sorted(rows, key=lambda r: r["resi"]):
            if r["n_cdks"] < label_min:
                continue
            L.append(f'label #1/{kc}:{r["resi"]} residues text "{r["label"]}" '
                     f'height 2.4 color black bgColor none')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--set", default="core7")
    ap.add_argument("--reference", default="CDK2",
                    help="kinase whose structure carries the projection (default CDK2/1QMZ)")
    ap.add_argument("--min-cdks", type=int, default=2)
    ap.add_argument("--sites", help="site table to read (default: MSA_recurrent_columns.csv; "
                                    "pass consensus_sites.csv to use the tier column)")
    ap.add_argument("--tiers", default="recurrent",
                    help="comma-separated tiers to draw, e.g. recurrent,strong_singleton")
    ap.add_argument("--tag", help="output directory suffix (default: consensus)")
    ap.add_argument("--label-min", type=int, default=3, dest="label_min",
                    help="label only sites shared by at least this many CDKs (default 3)")
    ap.add_argument("--out")
    a = ap.parse_args()

    src = a.sites or os.path.join(ROOT, "data", "processed", "lfc_fdr_tables",
                                  "resistance_patterns", a.set, "MSA_recurrent_columns.csv")
    if not os.path.exists(src):
        sys.exit(f"no site table at {src}")
    tiers = tuple(t.strip() for t in a.tiers.split(","))
    rows = load_recurrent(src, a.reference, a.min_cdks, tiers)
    if not rows:
        sys.exit("no recurrent positions map onto the reference structure")

    out = a.out or os.path.join(HERE, f"cxc_{a.set}_{a.tag or 'consensus'}")
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "consensus.cxc"), "w").write(build(rows, a.reference, False))
    open(os.path.join(out, "consensus_labeled.cxc"), "w").write(
        build(rows, a.reference, True, a.label_min))

    tag = os.path.basename(out)
    fig = os.path.join(ROOT, "figures", "chimerax", tag)
    os.makedirs(fig, exist_ok=True)
    rl = ["# Render the consensus panels; needs a GPU context, so run from the ChimeraX GUI",
          f"cd {HERE}", f"windowsize {WINDOW_SIZE[0]} {WINDOW_SIZE[1]}"]
    for name in ("consensus", "consensus_labeled"):
        rl.append(f"\nopen {tag}/{name}.cxc")
        rl.append(f"save {fig}/{name}.png width 3000 supersample 3 transparentBackground true")
    rl.append("\nclose session")
    open(os.path.join(out, "render_all.cxc"), "w").write("\n".join(rl) + "\n")

    print(f"{len(rows)} recurrent positions projected onto {a.reference} "
          f"({STRUCTURES[a.reference]['pdb']})")
    for r in rows:
        tag = "singleton" if r["tier"] == "strong_singleton" else f"{r['n_cdks']} CDKs"
        print(f"   {tag:>10}  col {r['aln_col']:>5}  {a.reference} {r['resi']:>4}  "
              f"LFC {r['max_LFC']:5.2f}  {r['label']:<11} {r['cdks']}")
    print(f"wrote {out}/consensus.cxc, consensus_labeled.cxc, render_all.cxc")


if __name__ == "__main__":
    main()
