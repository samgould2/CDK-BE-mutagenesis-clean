"""
Generate the ChimeraX panel for figure 2c: CDK9/cyclin T1 with 2b's variants.

Writes ./cxc/CDK9_fig2b.cxc and CDK9_fig2b_labeled.cxc -- the CDK9 panel from
generate_cxc.py, with one difference:

    * the marked residues are the five figure 2b names
      (cdk9_fig2b_hit_residues.csv, built by build_cdk9_fig2b_hits.py from 2b's
      own selection), not the sixteen all-condition CDK9 positions in
      hit_residues.csv that figure 1f's CDK9.png marks

Everything else -- 8K5R, chains A and B, the per-gene colour, the catalytic
domain fade, KB-0742 as sticks, lighting, camera matrix, pull-back -- comes
from cdk_config.py, so this panel drops in beside the existing ones.

**This is a rebuild, not a recovery.** The published 2c was made in an earlier
ChimeraX session that is not in any of the source repositories; the only
candidates are three unreadable `.cxs` files under notebooks/10_PyMOL. What
this script produces is the panel 2c describes, drawn in the convention every
other structure panel here uses. See docs/DISCREPANCIES.md item 30.

Usage:  python3 scripts/chimerax/build_cdk9_fig2b_hits.py
        python3 scripts/chimerax/generate_cdk9_fig2b.py
        python3 scripts/chimerax/render.py CDK9_fig2b CDK9_fig2b_labeled
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cdk_config import (STRUCTURES, ALIGN_REFERENCE, CDK_COLORS, CYCLIN_COLOR,
                        HIT_COLOR, HIT_STYLE, NONCATALYTIC_TRANSPARENCY,
                        RENDER_PREAMBLE, CANONICAL_VIEW, ZOOM_OUT)

GENE = "CDK9"
HITS_CSV = os.path.join(HERE, "cdk9_fig2b_hit_residues.csv")
OUT = os.path.join(HERE, "cxc")

#: same label convention as the CDK7 panel: scene units, so the text scales
#: with the structure rather than the window, and no background panel
LABEL_HEIGHT = 2.2
LABEL_COLOR = "black"


def load_hits():
    """position -> {'variants': 'C106Y', 'wt': 'C'}, from the residue table."""
    by_pos = {}
    for r in csv.DictReader(open(HITS_CSV)):
        p = int(r["position"])
        by_pos.setdefault(p, dict(variants=set(), wt=r["wt"]))["variants"].add(r["variant"])
    return {p: dict(variants=",".join(sorted(v["variants"])), wt=v["wt"])
            for p, v in sorted(by_pos.items())}


def build(labeled=False):
    cfg = STRUCTURES[GENE]
    ref = STRUCTURES[ALIGN_REFERENCE]
    kc = cfg["kinase_chain"]
    cyc = cfg["cyclin_chains"]
    lo, hi = cfg["kd"]
    color = CDK_COLORS[GENE]
    hits = load_hits()
    resis = ",".join(str(p) for p in hits)
    name = f"{GENE}_fig2b_labeled" if labeled else f"{GENE}_fig2b"

    L = []
    L.append("# " + "=" * 74)
    L.append(f"# Figure 2c: {GENE}/{cfg['cyclin_name']} ({cfg['pdb']}) with the "
             "figure 2b variants" + (", residues labeled" if labeled else ""))
    L.append("# Generated by generate_cdk9_fig2b.py -- edit that script, not this file.")
    L.append(f"# {cfg['note']}")
    L.append("# " + "=" * 74)
    L.append("close session")
    L.append("cd " + HERE)
    L.append("")

    # reference kept hidden so this panel lands in the same frame as the others
    L.append("# reference loaded hidden so this panel shares the common orientation")
    L.append(f"open structures/{ref['file']} name {ALIGN_REFERENCE}_ref")
    L.append("hide #1 target acsb")
    L.append("hide #1 models")

    L.append(f"\n# ---------------------------------------------------------------- {GENE}")
    L.append(f"open structures/{cfg['file']} name {GENE}")
    L.append("hide #2 target acsb")
    L.append("hide #2 models")

    # ---- kinase cartoon, catalytic core opaque and the rest faded back
    L.append(f"show #2/{kc} cartoon")
    L.append(f"color #2/{kc} {color} target c")
    L.append(f"transparency #2/{kc} & ~:{lo}-{hi} {NONCATALYTIC_TRANSPARENCY} cartoons")

    # ---- cyclin T1 surface
    cs = f"#2/{','.join(cyc)}"
    L.append(f"# {cfg['cyclin_name']} as surface")
    L.append(f"show {cs} atoms")
    L.append(f"surface {cs}")
    L.append(f"hide {cs} atoms")
    L.append(f"color {cs} {CYCLIN_COLOR} target s")

    # ---- ligand (KB-0742) sticks
    ls = f"#2/{kc} & :{cfg['ligand']}"
    L.append(f"# {cfg['ligand']} is KB-0742, the inhibitor figure 2a and 2d use")
    L.append(f"show {ls} target ab")
    L.append(f"style {ls} stick")
    L.append(f"color {ls} #909090 target ab")
    L.append(f"color {ls} byhetero")

    # ---- the figure 2b variants as red CPK spheres
    hs = f"#2/{kc}:{resis}"
    L.append(f"# {len(hits)} figure 2b positions: "
             + ", ".join(f"{h['wt']}{p} ({h['variants']})" for p, h in hits.items()))
    L.append(f"show {hs} atoms")
    # ChimeraX hides backbone atoms under a cartoon, so a hit with no side chain
    # past CA would otherwise show nothing but a recolored ribbon
    L.append(f"cartoon {hs} suppressBackboneDisplay false")
    L.append(f"style {hs} {HIT_STYLE}")
    L.append(f"color {hs} {HIT_COLOR} target ac")
    L.append(f"name {GENE}_fig2b_hits {hs}")

    L.append(f"name {GENE}_kinase #2/{kc}")
    L.append(f"name {GENE}_cyclin {cs}")

    L.append("")
    L.append(f"matchmaker #2/{kc} to #1/{ref['kinase_chain']}")

    # ---- shared look and camera
    L.append("\n# ---------------------------------------------------- look and camera")
    L.extend(RENDER_PREAMBLE.strip().splitlines())
    L.append("show #2 models")
    L.append("# mmCIF chain breaks otherwise draw dashed pseudobonds labelled")
    L.append('# "N residues", which land on top of the kinase in the render')
    L.append("label delete")
    L.append("hide #* target p")
    L.append("hide @@element=H target ab")

    # ---- residue labels, added after `label delete` so they survive it
    if labeled:
        L.append("\n# --------------------------------------------- residue labels")
        L.append("# one label per marked position, wild-type residue + number")
        L.append("# (e.g. L156), as bare black text with no background panel")
        for p, h in hits.items():
            L.append(f'label #2/{kc}:{p} residues text "{h["wt"]}{p}" '
                     f'height {LABEL_HEIGHT} color {LABEL_COLOR} bgColor none')

    L.append(f"view matrix camera {CANONICAL_VIEW}")
    L.append("# uniform pull-back so no panel clips at the frame edge")
    L.append(f"zoom {ZOOM_OUT}")
    L.append(f"# zoom on the variants:  view {GENE}_fig2b_hits")
    L.append("")
    L.append(f"# save figures/chimerax/{name}.png width 3000 supersample 3 "
             "transparentBackground true")

    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"{name}.cxc")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", path)
    return path


def write_render_script():
    """Companion render script, same shape as render_cdk7_sy5609.cxc."""
    fig = os.path.normpath(os.path.join(HERE, "..", "..", "figures", "chimerax"))
    R = ["# " + "=" * 74,
         f"# Render the figure 2c {GENE} panels to figures/chimerax/ at publication size",
         "# Generated by generate_cdk9_fig2b.py -- edit that script, not this file.",
         "# ChimeraX needs a real GPU context for `save`, so run this from the ChimeraX GUI",
         '#   (or `ChimeraX --exit --cmd "open cxc/render_cdk9_fig2b.cxc"`), not --nogui.',
         "# " + "=" * 74,
         "close session",
         "cd " + HERE,
         "# fixed aspect ratio so these panels match the others",
         "windowsize 1400 1400",
         ""]
    for name in (f"{GENE}_fig2b", f"{GENE}_fig2b_labeled"):
        R += [f"open cxc/{name}.cxc",
              f"save {fig}/{name}.png width 3000 supersample 3 transparentBackground true",
              "",
              "# and a zoomed view on the variant cluster",
              f"view {GENE}_fig2b_hits",
              "zoom 0.75",
              f"save {fig}/{name}_zoom.png width 3000 supersample 3 transparentBackground true",
              ""]
    R += ["close session", ""]

    rpath = os.path.join(OUT, "render_cdk9_fig2b.cxc")
    with open(rpath, "w") as fh:
        fh.write("\n".join(R))
    print("wrote", rpath)


if __name__ == "__main__":
    build(labeled=False)
    build(labeled=True)
    write_render_script()
    hits = load_hits()
    print(f"{len(hits)} positions:",
          ", ".join(f"{h['wt']}{p} ({h['variants']})" for p, h in hits.items()))
