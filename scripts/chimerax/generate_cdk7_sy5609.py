"""
Generate the ChimeraX panel for the CDK7 SY-5609 resistance variants.

Writes ./cxc/CDK7_SY5609.cxc -- the CDK7 panel from generate_cxc.py, with two
differences:

    * hits are the SY-5609-specific set from
      notebooks/09_analysis_and_viz/CDK7_SY5609_hits.ipynb
      (cdk7_sy5609_hit_residues.csv), not the all-condition set in
      hit_residues.csv
    * MAT1 (6XD3 chain H) is shown as a gray surface instead of being hidden

Everything else -- structure, chains, colors, catalytic-domain fade, ligand
sticks, lighting, camera matrix, pull-back -- comes from cdk_config.py, so this
panel drops in beside the existing ones.

Usage:  python3 generate_cdk7_sy5609.py
        then, in ChimeraX:  open cxc/CDK7_SY5609.cxc
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cdk_config import (STRUCTURES, ALIGN_REFERENCE, CDK_COLORS, CYCLIN_COLOR,
                        OTHER_CHAIN_COLOR, HIT_COLOR, HIT_STYLE,
                        NONCATALYTIC_TRANSPARENCY, RENDER_PREAMBLE,
                        CANONICAL_VIEW, ZOOM_OUT)

GENE = "CDK7"
HITS_CSV = os.path.join(HERE, "cdk7_sy5609_hit_residues.csv")
OUT = os.path.join(HERE, "cxc")

# MAT1 is the third CAK subunit.  The cyclin partner is already wheat, so MAT1
# takes the repo's neutral "other chain" gray; it is drawn as a surface so the
# two partner subunits read the same way.
MAT1_CHAIN = "H"
MAT1_COLOR = OTHER_CHAIN_COLOR

# residue labels for the labeled variant.  Height is in scene units (A), so it
# scales with the structure rather than the window; 2.2 A reads cleanly at the
# 3000 px render width used for every other panel.  No background: bare black
# text, so the labels sit on the structure rather than masking it.
LABEL_HEIGHT = 2.2
LABEL_COLOR = "black"


def load_hits():
    """position -> {'variants': 'L18F', 'wt': 'L'}, from the notebook's residue table."""
    rows = list(csv.DictReader(open(HITS_CSV)))
    by_pos = {}
    for r in rows:
        p = int(r["position"])
        by_pos.setdefault(p, dict(variants=set(), wt=r["wt"]))["variants"].add(r["variant"])
    return {p: dict(variants=",".join(sorted(v["variants"])), wt=v["wt"])
            for p, v in sorted(by_pos.items())}


def build(labeled=False):
    cfg = STRUCTURES[GENE]
    ref = STRUCTURES[ALIGN_REFERENCE]
    kc = cfg["kinase_chain"]
    cyc = cfg["cyclin_chains"]
    lo, hi = cfg["kd"]
    color = CDK_COLORS[GENE]
    hits = load_hits()
    resis = ",".join(str(p) for p in hits)
    name = f"{GENE}_SY5609_labeled" if labeled else f"{GENE}_SY5609"

    L = []
    L.append("# " + "=" * 74)
    L.append(f"# {GENE} SY-5609 resistance variants ({cfg['pdb']}), with MAT1 shown"
             + (", residues labeled" if labeled else ""))
    L.append("# Generated by generate_cdk7_sy5609.py -- edit that script, not this file.")
    L.append(f"# {cfg['note']}")
    L.append("# " + "=" * 74)
    L.append("close session")
    L.append("cd " + HERE)
    L.append("")

    # reference kept hidden so this panel lands in the same frame as the others
    L.append("# reference loaded hidden so this panel shares the common orientation")
    L.append(f"open structures/{ref['file']} name {ALIGN_REFERENCE}_ref")
    L.append("hide #1 target acsb")
    L.append("hide #1 models")

    L.append(f"\n# ---------------------------------------------------------------- {GENE}")
    L.append(f"open structures/{cfg['file']} name {GENE}")
    L.append("hide #2 target acsb")
    L.append("hide #2 models")

    # ---- kinase cartoon, catalytic core opaque and the rest faded back
    L.append(f"show #2/{kc} cartoon")
    L.append(f"color #2/{kc} {color} target c")
    L.append(f"transparency #2/{kc} & ~:{lo}-{hi} {NONCATALYTIC_TRANSPARENCY} cartoons")

    # ---- cyclin H surface
    cs = f"#2/{','.join(cyc)}"
    L.append(f"# {cfg['cyclin_name']} as surface")
    L.append(f"show {cs} atoms")
    L.append(f"surface {cs}")
    L.append(f"hide {cs} atoms")
    L.append(f"color {cs} {CYCLIN_COLOR} target s")

    # ---- MAT1 surface: the change relative to the CDK7 panel in generate_cxc.py
    ms = f"#2/{MAT1_CHAIN}"
    L.append("# MAT1 (the third CAK subunit) as a gray surface.  Only its")
    L.append("# C-terminal 244-308 is ordered in 6XD3; the rest is absent from the model.")
    L.append(f"show {ms} atoms")
    L.append(f"surface {ms}")
    L.append(f"hide {ms} atoms")
    L.append(f"color {ms} {MAT1_COLOR} target s")
    L.append(f"name {GENE}_MAT1 {ms}")

    # ---- ligand (THZ1) sticks
    ls = f"#2/{kc} & :{cfg['ligand']}"
    L.append(f"show {ls} target ab")
    L.append(f"style {ls} stick")
    L.append(f"color {ls} #909090 target ab")
    L.append(f"color {ls} byhetero")

    # ---- SY-5609 hits as red CPK spheres
    hs = f"#2/{kc}:{resis}"
    L.append(f"# {len(hits)} SY-5609 resistance positions: "
             + ", ".join(f"{p} {h['variants']}" for p, h in hits.items()))
    L.append(f"show {hs} atoms")
    # ChimeraX hides backbone atoms under a cartoon, so a hit with no side chain
    # past CA would otherwise show nothing but a recolored ribbon
    L.append(f"cartoon {hs} suppressBackboneDisplay false")
    L.append(f"style {hs} {HIT_STYLE}")
    L.append(f"color {hs} {HIT_COLOR} target ac")
    L.append(f"name {GENE}_SY5609_hits {hs}")

    L.append(f"name {GENE}_kinase #2/{kc}")
    L.append(f"name {GENE}_cyclin {cs}")

    L.append("")
    L.append(f"matchmaker #2/{kc} to #1/{ref['kinase_chain']}")

    # ---- shared look and camera
    L.append("\n# ---------------------------------------------------- look and camera")
    L.extend(RENDER_PREAMBLE.strip().splitlines())
    L.append("show #2 models")
    L.append("# mmCIF chain breaks otherwise draw dashed pseudobonds labelled")
    L.append('# "N residues", which land on top of the kinase in the render')
    L.append("label delete")
    L.append("hide #* target p")
    L.append("hide @@element=H target ab")

    # ---- residue labels, added after `label delete` so they survive it
    if labeled:
        L.append("\n# --------------------------------------------- residue labels")
        L.append("# one label per hit position, wild-type residue + number (e.g. L18),")
        L.append("# as bare black text with no background panel")
        for p, h in hits.items():
            L.append(f'label #2/{kc}:{p} residues text "{h["wt"]}{p}" '
                     f'height {LABEL_HEIGHT} color {LABEL_COLOR} bgColor none')

    L.append(f"view matrix camera {CANONICAL_VIEW}")
    L.append("# uniform pull-back so no panel clips at the frame edge")
    L.append(f"zoom {ZOOM_OUT}")
    L.append(f"# zoom on the hits:  view {GENE}_SY5609_hits")
    L.append("")
    L.append(f"# save figures/chimerax/{name}.png width 3000 supersample 3 transparentBackground true")

    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"{name}.cxc")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", path)
    return path

def write_render_script():
    """Companion render script, same shape as render_all.cxc."""
    fig = os.path.normpath(os.path.join(HERE, "..", "..", "figures", "chimerax"))
    R = ["# " + "=" * 74,
         f"# Render the {GENE} SY-5609 panels to figures/chimerax/ at publication size",
         "# Generated by generate_cdk7_sy5609.py -- edit that script, not this file.",
         "# ChimeraX needs a real GPU context for `save`, so run this from the ChimeraX GUI",
         '#   (or `ChimeraX --exit --cmd "open cxc/render_cdk7_sy5609.cxc"`), not --nogui.',
         "# " + "=" * 74,
         "close session",
         "cd " + HERE,
         "# fixed aspect ratio so these panels match the others",
         "windowsize 1400 1400",
         ""]
    for name in (f"{GENE}_SY5609", f"{GENE}_SY5609_labeled"):
        R += [f"open cxc/{name}.cxc",
              f"save {fig}/{name}.png width 3000 supersample 3 transparentBackground true",
              "",
              "# and a zoomed view on the hit cluster",
              f"view {GENE}_SY5609_hits",
              "zoom 0.75",
              f"save {fig}/{name}_zoom.png width 3000 supersample 3 transparentBackground true",
              ""]
    R += ["close session", ""]

    rpath = os.path.join(OUT, "render_cdk7_sy5609.cxc")
    with open(rpath, "w") as fh:
        fh.write("\n".join(R))
    print("wrote", rpath)


if __name__ == "__main__":
    build(labeled=False)
    build(labeled=True)
    write_render_script()
    hits = load_hits()
    print(f"{len(hits)} positions:",
          ", ".join(f"{h['wt']}{p} ({h['variants']})" for p, h in hits.items()))
